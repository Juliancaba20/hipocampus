function normalizarTexto(str = '') {
  return String(str)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase();
}

export function buscarIconos(consulta = '', categoria = 'todas') {
  const q = normalizarTexto(consulta.trim());
  return CATALOGO_ICONOS.filter((ico) => {
    if (categoria !== 'todas' && ico.categoria !== categoria) return false;
    if (!q) return true;
    const nombreNorm = normalizarTexto(ico.nombre);
    const palabrasNorm = normalizarTexto(ico.palabras);
    return nombreNorm.includes(q) || palabrasNorm.includes(q);
  });
}

